    private void tambahBuku() {

    Buku buku = new BukuDialog(
        this,
        "Tambah Buku",
        null
    ).tampilkanDialog();

    if (buku != null) {
        model.tambahBuku(buku);
        perbaruiStatus();
    }
}
    
    private void ubahBuku() {

    int baris = ambilBarisTerpilih();

    if (baris < 0) {
        return;
    }

    Buku buku = new BukuDialog(
        this,
        "Ubah Buku",
        model.ambilBuku(baris)
    ).tampilkanDialog();

    if (buku != null) {
        model.ubahBuku(baris, buku);
        perbaruiStatus();
    }
}
    
    private void inisialisasiTabel() {

    bukuTable.setModel(model);

    sorter = new javax.swing.table.TableRowSorter<>(model);
    bukuTable.setRowSorter(sorter);

    bukuTable.setSelectionMode(
        javax.swing.ListSelectionModel.SINGLE_SELECTION
    );

    bukuTable.getColumnModel().getColumn(0).setPreferredWidth(90);
    bukuTable.getColumnModel().getColumn(1).setPreferredWidth(250);
    bukuTable.getColumnModel().getColumn(2).setPreferredWidth(160);
    bukuTable.getColumnModel().getColumn(3).setPreferredWidth(100);
    bukuTable.getColumnModel().getColumn(4).setPreferredWidth(100);
}
    
    private int ambilBarisTerpilih() {

    int barisView = bukuTable.getSelectedRow();

    if (barisView < 0) {
        return -1;
    }

    return bukuTable.convertRowIndexToModel(barisView);
}
    
    private void perbaruiStatus() {

    informasiLabel.setText(
        "Menampilkan " + model.getRowCount()
        + " buku | Tersedia: " + model.hitungBukuTersedia()
    );
}
    
    private void hapusBuku() {

    int baris = ambilBarisTerpilih();

    if (baris < 0) {
        return;
    }

    Buku buku = model.ambilBuku(baris);

    int konfirmasi = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Apakah kamu yakin ingin menghapus buku \""
            + buku.getJudul() + "\"?",
        "Konfirmasi Hapus",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (konfirmasi == javax.swing.JOptionPane.YES_OPTION) {
        model.hapusBuku(baris);
        perbaruiStatus();
    }
}
    
    private void cariBuku() {

    String kataKunci = cariField.getText().trim();

    if (kataKunci.isEmpty()) {
        sorter.setRowFilter(null);
    } else {
        sorter.setRowFilter(
            javax.swing.RowFilter.regexFilter(
                "(?i)" + java.util.regex.Pattern.quote(kataKunci),
                0, 1, 2
            )
        );
    }
}
    
    private void aturEvent() {

    tambahButton.addActionListener(e -> tambahBuku());
    editButton.addActionListener(e -> ubahBuku());
    hapusbutton.addActionListener(e -> hapusBuku());

    tambahItem.addActionListener(e -> tambahBuku());
    editItem.addActionListener(e -> ubahBuku());
    hapusItem.addActionListener(e -> hapusBuku());

    keluarItem.addActionListener(e -> dispose());

    bukuTable.getSelectionModel().addListSelectionListener(e -> {

        if (!e.getValueIsAdjusting()) {
            boolean terpilih = bukuTable.getSelectedRow() >= 0;

            editButton.setEnabled(terpilih);
            hapusbutton.setEnabled(terpilih);

            editItem.setEnabled(terpilih);
            hapusItem.setEnabled(terpilih);
        }
    });
}
   
