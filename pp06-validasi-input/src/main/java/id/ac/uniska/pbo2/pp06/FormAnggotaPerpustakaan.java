    private void tampilkanPesan(
        javax.swing.JComponent komponen,
        javax.swing.JLabel label,
        String pesan,
        javax.swing.border.Border borderAwal) {

    if (pesan == null) {
        label.setText(" ");
        komponen.setBorder(borderAwal);
    } else {
        label.setText(pesan);
        label.setForeground(new java.awt.Color(200, 0, 0));
        komponen.setBorder(
            javax.swing.BorderFactory.createLineBorder(
                new java.awt.Color(220, 50, 50), 1
            )
        );
    }
}

// Menghapus pesan kesalahan dan mengembalikan border
private void bersihkanPesan(
        javax.swing.JLabel label,
        javax.swing.JComponent komponen,
        javax.swing.border.Border borderAwal) {

    label.setText(" ");
    komponen.setBorder(borderAwal);
}

// Validasi NPM
private String periksaNpm() {
    String pesan = Validator.npm(npmField.getText());

    tampilkanPesan(npmField, npmPesanLabel, pesan, borderNpm);

    return pesan;
}

// Validasi nama
private String periksaNama() {
    String pesan = Validator.nama(namaField.getText());

    tampilkanPesan(namaField, namaPesanLabel, pesan, borderNama);

    return pesan;
}

// Validasi email
private String periksaEmail() {
    String pesan = Validator.email(emailField.getText());

    tampilkanPesan(emailField, emailPesanLabel, pesan, borderEmail);

    return pesan;
}

// Validasi nomor HP
private String periksaHp() {
    String pesan = Validator.nomorHp(hpField.getText());

    tampilkanPesan(hpField, hpPesanLabel, pesan, borderHp);

    return pesan;
}

// Validasi pilihan program studi
private String periksaProdi() {
    String pilihan = (String) programStudiCombo.getSelectedItem();
    String pesan = null;

    if (pilihan == null || pilihan.isBlank()) {
        pesan = "Program studi wajib dipilih";
    }

    tampilkanPesan(
        programStudiCombo,
        prodiPesanLabel,
        pesan,
        borderProdi
    );

    return pesan;
}

// Memeriksa semua isian saat tombol Daftar ditekan
private void daftar() {

    int jumlahKesalahan = 0;
    java.awt.Component fokusPertama = null;

    String pesanNpm = periksaNpm();
    if (pesanNpm != null) {
        jumlahKesalahan++;
        fokusPertama = npmField;
    }

    String pesanNama = periksaNama();
    if (pesanNama != null) {
        jumlahKesalahan++;
        if (fokusPertama == null) {
            fokusPertama = namaField;
        }
    }

    String pesanProdi = periksaProdi();
    if (pesanProdi != null) {
        jumlahKesalahan++;
        if (fokusPertama == null) {
            fokusPertama = programStudiCombo;
        }
    }

    String pesanEmail = periksaEmail();
    if (pesanEmail != null) {
        jumlahKesalahan++;
        if (fokusPertama == null) {
            fokusPertama = emailField;
        }
    }

    String pesanHp = periksaHp();
    if (pesanHp != null) {
        jumlahKesalahan++;
        if (fokusPertama == null) {
            fokusPertama = hpField;
        }
    }

    if (jumlahKesalahan > 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Ditemukan " + jumlahKesalahan
            + " kesalahan pada formulir.\n"
            + "Silakan periksa kembali isian yang ditandai merah.",
            "Validasi Form",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );

        if (fokusPertama != null) {
            fokusPertama.requestFocusInWindow();
        }

        return;
    }

    if (!sayaSetyjuCheck.isSelected()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Anda harus menyetujui tata tertib perpustakaan.",
            "Persetujuan",
            javax.swing.JOptionPane.WARNING_MESSAGE
        );
        sayaSetyjuCheck.requestFocusInWindow();
        return;
    }

    String jenisAnggota = "Belum dipilih";

    if (mahasiswaRb.isSelected()) {
        jenisAnggota = "Mahasiswa";
    } else if (dosenRb.isSelected()) {
        jenisAnggota = "Dosen";
    } else if (umuumRb.isSelected()) {
        jenisAnggota = "Umum";
    }

    String ringkasan =
        "Pendaftaran berhasil!\n\n"
        + "NPM: " + npmField.getText() + "\n"
        + "Nama: " + namaField.getText() + "\n"
        + "Program Studi: " + programStudiCombo.getSelectedItem() + "\n"
        + "Jenis Anggota: " + jenisAnggota + "\n"
        + "Email: " + emailField.getText() + "\n"
        + "Nomor HP: " + hpField.getText() + "\n"
        + "Alamat: " + alamatArea.getText();

    javax.swing.JOptionPane.showMessageDialog(
        this,
        ringkasan,
        "Ringkasan Pendaftaran",
        javax.swing.JOptionPane.INFORMATION_MESSAGE
    );
}

// Mengosongkan seluruh isian form
private void kosongkanForm() {

    npmField.setText("");
    namaField.setText("");
    emailField.setText("");
    hpField.setText("");
    alamatArea.setText("");

    programStudiCombo.setSelectedIndex(0);
    jenisAnggotaButtonGroup.clearSelection();

    sayaSetyjuCheck.setSelected(false);
    daftarButton.setEnabled(false);

    bersihkanPesan(npmPesanLabel, npmField, borderNpm);
    bersihkanPesan(namaPesanLabel, namaField, borderNama);
    bersihkanPesan(emailPesanLabel, emailField, borderEmail);
    bersihkanPesan(hpPesanLabel, hpField, borderHp);
    bersihkanPesan(prodiPesanLabel, programStudiCombo, borderProdi);

    alamatPesanLabel.setText(" ");

    npmField.requestFocusInWindow();
}

// Konfirmasi sebelum mengosongkan form
private void batal() {

    boolean adaData =
        !npmField.getText().isBlank()
        || !namaField.getText().isBlank()
        || !emailField.getText().isBlank()
        || !hpField.getText().isBlank()
        || !alamatArea.getText().isBlank()
        || jenisAnggotaButtonGroup.getSelection() != null
        || sayaSetyjuCheck.isSelected()
        || programStudiCombo.getSelectedIndex() != 0;

    if (!adaData) {
        kosongkanForm();
        return;
    }

    int pilihan = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Apakah Anda yakin ingin mengosongkan seluruh data?",
        "Konfirmasi Pembatalan",
        javax.swing.JOptionPane.YES_NO_OPTION,
        javax.swing.JOptionPane.QUESTION_MESSAGE
    );

    if (pilihan == javax.swing.JOptionPane.YES_OPTION) {
        kosongkanForm();
    }
    }

